local M = assert(loadfile(arg[1]))()
local s = M.new()
assert(M.observe(s, {in_mission=false}) == nil)
assert(M.observe(s, {in_mission=true, identity=100}) == 'started')
assert(M.observe(s, nil) == nil and s.active)
assert(M.observe(s, {in_mission=false}) == nil and s.active)
assert(M.observe(s, {in_mission=true, identity=100}) == nil)
assert(M.observe(s, {in_mission=false}) == nil)
assert(M.observe(s, nil) == nil)
assert(M.observe(s, {in_mission=false}) == nil)
assert(M.observe(s, {in_mission=false}) == 'ended' and not s.active)
assert(M.observe(s, {in_mission=false}) == nil)
assert(M.observe(s, {in_mission=true, identity=200}) == 'started')
assert(M.observe(s, {in_mission=true, identity=201}) == 'started')
assert(M.observe(s, {in_mission=true}) == nil and s.identity == 201)
return 'PASS: independent mission boundaries, uncertain reads, end lock and new mission identity'
